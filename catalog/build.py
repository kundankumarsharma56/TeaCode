"""Validate the catalog by EXECUTING every reference solution, then emit the Flyway migration and a report.

    python3 catalog/build.py            # validate, write V9 migration + REPORT.md, exit 1 on any issue
    python3 catalog/build.py --check    # validate only (what CI runs); writes nothing

Exit status is non-zero if any problem fails validation, so an invalid problem can never reach the migration.
"""
import glob
import importlib
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import lib  # noqa: E402

MIGRATION = os.path.join(HERE, "..", "backend", "src", "main", "resources", "db", "migration", "V9__curated_problem_catalog.sql")
V6_LEGACY_SLUG_COUNT = 510  # entries created by migration V6


def load():
    probs = []
    for path in sorted(glob.glob(os.path.join(HERE, "p_*.py"))):
        mod = importlib.import_module(os.path.basename(path)[:-3])
        probs.extend(mod.PROBLEMS)
    return probs


def versions():
    py = sys.version.split()[0]
    gpp = subprocess.run(["g++", "--version"], capture_output=True, text=True).stdout.splitlines()[0]
    return {"python": f"CPython {py}", "cpp": f"{gpp.split(')')[-1].strip() and 'g++ ' + gpp.split()[-1]} -std=c++17 -O2"}


def main():
    check_only = "--check" in sys.argv
    t0 = time.time()
    probs = load()
    results, glob_issues = lib.validate(probs)
    failed = [r for r in results if r.issues]
    by_diff, by_tag = {}, {}
    for r in results:
        by_diff[r.problem.difficulty] = by_diff.get(r.problem.difficulty, 0) + 1
        for t in r.problem.tags:
            by_tag[t] = by_tag.get(t, 0) + 1
    legacy = [r for r in results if r.problem.legacy]
    new = [r for r in results if not r.problem.legacy]
    print(f"problems: {len(results)} (legacy rewritten {len(legacy)}, new {len(new)}); failing: {len(failed)}; cross-problem issues: {len(glob_issues)}")
    for r in failed:
        for i in r.issues:
            print(f"  FAIL {r.problem.slug}: {i}")
    for g in glob_issues:
        print(f"  DUP  {g}")
    tests = sum(r.tests_run for r in results)
    print(f"executed {tests} test runs x 2 implementations in {time.time() - t0:.1f}s")
    if failed or glob_issues:
        sys.exit(1)
    if check_only:
        return
    ver = versions()
    sql = lib.sql_for(results, [], ver)
    with open(MIGRATION, "w", encoding="utf-8", newline="\n") as f:
        f.write(sql)
    lines = ["# Problem catalog validation report", "",
             f"Generated by `catalog/build.py` (Python {sys.version.split()[0]}, {ver['cpp']}). Every number below was produced by executing the reference solutions.", "",
             "## Summary", "",
             "| Metric | Value |", "|---|---|",
             f"| Entries found in migration V6 | {V6_LEGACY_SLUG_COUNT} |",
             f"| Distinct problems among them (by objective) | {len(legacy)} |",
             f"| Duplicate copies archived by V9 | {V6_LEGACY_SLUG_COUNT - len(legacy)} |",
             f"| Legacy problems rewritten in place | {len(legacy)} |",
             f"| New unique problems added | {len(new)} |",
             f"| Published problems after V9 | {len(results)} |",
             f"| Problems passing validation | {len(results) - len(failed)} |",
             f"| Problems failing validation | {len(failed)} |",
             f"| Duplicate pairs detected (title, statement, tests, solution) | {len(glob_issues)} |",
             f"| Problems with >= 2 examples | {sum(1 for r in results if len(r.problem.examples) >= 2)} |",
             f"| Problems with >= 2 sample tests (= examples) | {sum(1 for r in results if len(r.problem.examples) >= 2)} |",
             f"| Problems with hidden tests | {sum(1 for r in results if len(r.problem.hidden_inputs) >= 6)} |",
             f"| Reference solutions executed and verified | {2 * len(results)} (Python and C++ for every problem) |",
             f"| Test executions (public + hidden) x 2 implementations | {tests * 2} |",
             f"| Starter-code templates | {len(lib.STARTER)} languages x {len(results)} problems |", "",
             "Difficulty: " + ", ".join(f"{k} {v}" for k, v in sorted(by_diff.items())), "",
             "Topics: " + ", ".join(f"{k} {v}" for k, v in sorted(by_tag.items())), "",
             "## Problems", "", "| Slug | Title | Difficulty | Tags | Examples | Hidden | Python worst ms |", "|---|---|---|---|---|---|---|"]
    for r in results:
        p = r.problem
        lines.append(f"| `{p.slug}` | {p.title} | {p.difficulty} | {', '.join(p.tags)} | {len(p.examples)} | {len(p.hidden_inputs)} | {r.py_ms:.0f} |")
    lines += ["", "## What was and was not verified", "",
              "- Verified by execution: every expected output (Python vs independent C++ implementation, identical token output on every test); every public example's stated output; constraints of every input (per-problem validators); duplicate detection (titles, statements, hidden suites, solutions).",
              "- Not verified here: reference solutions in the other 13 supported languages (only Python and C++ are stored); the starter templates for languages whose toolchain is not installed in this environment (see docs); behaviour of the JDoodle execution provider.",
              ""]
    open(os.path.join(HERE, "REPORT.md"), "w", encoding="utf-8").write("\n".join(lines))
    print("wrote", os.path.relpath(MIGRATION, HERE), f"({len(sql) / 1e6:.2f} MB) and REPORT.md")


if __name__ == "__main__":
    main()
